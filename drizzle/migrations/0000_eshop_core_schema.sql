-- single default per user
create or replace function public.enforce_single_default()
returns trigger language plpgsql set search_path = public as $$
begin
  if new.is_default then
    execute format('update public.%I set is_default = false where user_id = $1 and id <> $2', TG_TABLE_NAME)
      using new.user_id, new.id;
  end if;
  return new;
end $$;
create trigger addresses_single_default after insert or update of is_default on public.addresses
for each row when (new.is_default) execute function public.enforce_single_default();
create trigger payment_single_default after insert or update of is_default on public.payment_methods
for each row when (new.is_default) execute function public.enforce_single_default();

