create or replace function public.can_review(_line uuid, _product int)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.order_lines l
    join public.shop_orders o on o.id = l.order_id
    join public.product_items pi on pi.id = l.product_item_id
    where l.id = _line and o.user_id = auth.uid() and o.status_id = 3 and pi.product_id = _product
  )
$$;
create policy "review purchased" on public.reviews for insert to authenticated
  with check (user_id = auth.uid() and public.can_review(order_line_id, product_id));

-- PRICING with active promotions
create or replace function public.item_price(_item int)
returns numeric language sql stable set search_path = public as $$
  select round(pi.price * (1 - coalesce((
    select max(pr.discount_rate) from public.promotions pr
    join public.promotion_categories pc on pc.promotion_id = pr.id
    join public.products p on p.id = pi.product_id
    where pc.category_id = p.category_id and now() between pr.start_date and pr.end_date
  ), 0) / 100), 2)
  from public.product_items pi where pi.id = _item
$$;

-- PLACE ORDER: atomically checks stock, decrements, creates order, clears cart
create or replace function public.place_order(_address uuid, _shipping int, _payment uuid)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  addr public.addresses;
  pm record;
  ship public.shipping_methods;
  oid uuid;
  subtotal numeric := 0;
  r record;
begin
  if uid is null then raise exception 'Harus masuk terlebih dahulu'; end if;
  select * into addr from public.addresses where id = _address and user_id = uid;
  if not found then raise exception 'Alamat tidak ditemukan'; end if;
  select m.*, t.name as type_name into pm from public.payment_methods m join public.payment_types t on t.id = m.payment_type_id
    where m.id = _payment and m.user_id = uid;
  if not found then raise exception 'Metode pembayaran tidak ditemukan'; end if;
  select * into ship from public.shipping_methods where id = _shipping;
  if not found then raise exception 'Metode pengiriman tidak ditemukan'; end if;
  if not exists (select 1 from public.cart_items where user_id = uid) then raise exception 'Keranjang kosong'; end if;

  insert into public.shop_orders (user_id, payment_method_id, payment_label, shipping_address, shipping_method_id, shipping_price, order_total, status_id)
  values (uid, pm.id, pm.type_name || ' ' || pm.provider || ' •••• ' || pm.account_last4,
          addr.recipient || ', ' || addr.street || ', ' || addr.city || ' ' || addr.postal_code || ', ' || addr.country,
          ship.id, ship.price, 0, 1)
  returning id into oid;

  for r in select c.product_item_id, c.qty, pi.qty_in_stock, pi.sku from public.cart_items c
           join public.product_items pi on pi.id = c.product_item_id
           where c.user_id = uid for update of pi loop
    if r.qty_in_stock < r.qty then raise exception 'Stok tidak cukup untuk %', r.sku; end if;
    update public.product_items set qty_in_stock = qty_in_stock - r.qty where id = r.product_item_id;
    insert into public.order_lines (order_id, product_item_id, qty, price) values (oid, r.product_item_id, r.qty, public.item_price(r.product_item_id));
    subtotal := subtotal + public.item_price(r.product_item_id) * r.qty;
  end loop;

  update public.shop_orders set order_total = subtotal + ship.price where id = oid;
  delete from public.cart_items where user_id = uid;
  return oid;
end $$;
revoke execute on function public.place_order(uuid, int, uuid) from public, anon;
grant execute on function public.place_order(uuid, int, uuid) to authenticated;

create or replace function public.set_order_status(_order uuid, _status int)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.has_role(auth.uid(), 'admin') then raise exception 'Hanya admin'; end if;
  update public.shop_orders set status_id = _status where id = _order;
end $$;
revoke execute on function public.set_order_status(uuid, int) from public, anon;
grant execute on function public.set_order_status(uuid, int) to authenticated;

